/**
 * `customerPhone`/`Business.phone` — это НЕ телефон, используемый самим
 * приложением для звонка/SMS (нет ни одной такой интеграции), а просто
 * контактная строка, которую владелец бизнеса потом читает глазами и
 * набирает сам. `class-validator`'s `@IsPhoneNumber(undefined)` (без явного
 * региона) требует строгий международный формат СО знаком `+` — реальный
 * пользователь, печатающий свой номер в привычном локальном формате без "+"
 * (например, украинский "380958887722" вместо "+380958887722"), получал
 * непонятный "Некорректный номер телефона" и не мог оформить заказ вообще
 * (см. отчёт пользователя — заказ падал именно на этом поле). Валидация
 * здесь — просто "похоже на телефон" (цифры/пробелы/дефисы/скобки,
 * опциональный "+", хотя бы 5 цифр суммарно), не строгая E.164-проверка с
 * определением страны.
 */
export const LOOSE_PHONE_PATTERN = /^(?=(?:.*\d){5,})[+\d\s()-]{5,20}$/;

export const LOOSE_PHONE_MESSAGE = 'Некорректный номер телефона';
