/**
 * Generalized Second Price — закрывает §68.8's "не настоящий второй-цена-
 * аукцион" (v1 было honest highest-bid-wins, победитель платил СОБСТВЕННУЮ
 * ставку). Победитель платит следующую по убыванию ОТЛИЧНУЮ эффективную
 * ставку среди конкурентов, а не свою — классический truthful-bidding
 * механизм: у рекламодателя больше нет стимула занижать/угадывать чужую
 * ставку, честная максимальная готовность платить — сама по себе
 * оптимальная стратегия.
 *
 * Ставки конкурентов, РАВНЫЕ собственной ставке победителя (в том числе
 * другие креативы этой же кампании, если у неё их несколько — тот же
 * `calculateEffectiveCpmCents` для всех креативов одной кампании), явно
 * пропускаются через `bid < winnerBid`, не `bid <= winnerBid` — иначе
 * кампания "конкурировала" бы сама с собой, а не с реальным соперником.
 * Если конкурента со СТРОГО меньшей ставкой нет вообще (монополия на это
 * место прямо сейчас, либо единственный кандидат в пуле) — победитель
 * платит собственную ставку (первая цена): платить меньше относительно
 * нечего.
 *
 * Одна и та же функция обслуживает оба реальных вызывающих кода:
 * `AdEngineService.selectCreative`'s единственного победителя (полный пул
 * кандидатов — его же конкуренты) и `selectCreativesForFeed`'s N
 * победителей (для каждого — тот же полный пул, включая других
 * победителей: место 2 честно "конкурирует" с местом 1 наравне со всеми
 * остальными кандидатами пула) — тот же общепринятый generalized second
 * price для мультислотовой выдачи, что используют настоящие рекламные сети.
 *
 * Чистая функция без Prisma/NestJS — та же причина, что у `effective-bid.ts`.
 */
export function calculateClearingPriceCents(
  winnerEffectiveBidCents: number,
  poolEffectiveBidsCents: number[],
): number {
  const runnerUpBidCents = poolEffectiveBidsCents.reduce(
    (best, bid) => (bid < winnerEffectiveBidCents && bid > best ? bid : best),
    -Infinity,
  );
  return runnerUpBidCents === -Infinity ? winnerEffectiveBidCents : runnerUpBidCents;
}
