import geoip from 'geoip-lite';

/**
 * Настоящее региональное таргетирование (закрывает §68's "restricted-
 * category/age/region rule engine" в части region — владелец явно попросил
 * реальное ограничение, не декларативный флаг, в отличие от возраста, см.
 * `AdCampaign.isAdultContent`'s комментарий). `geoip-lite` — офлайн-
 * библиотека (данные уровня страны на основе MaxMind GeoLite2, вшиты в сам
 * npm-пакет), не внешний сервис — ни сетевого вызова, ни ключа API на
 * каждый показ, в отличие от `ExchangeRatesService` (тому Redis-кэш нужен
 * именно потому, что это внешний HTTP-вызов; здесь кэшировать нечего).
 *
 * Возвращает ISO 3166-1 alpha-2 код страны (`'US'`, `'UA'`) или `null` —
 * локальные/приватные IP (localhost, Docker-сеть, `127.0.0.1`) НЕ
 * резолвятся в страну (у `geoip-lite` просто нет данных), это ожидаемо в
 * dev-окружении и при прямом подключении без реального прокси. Вызывающий
 * (`AdEngineService`) обязан явно решить, что делать с `null` — см. её
 * комментарий про безопасный дефолт "не показывать гео-ограниченную
 * рекламу неопознанному посетителю".
 *
 * `ip` приходит из Express'ового `request.ip` (см. `PublicSitesController`/
 * `FeedAdsController`) — за настоящим обратным прокси в проде это НЕ адрес
 * посетителя, если `trust proxy` не настроен под ту топологию (см.
 * `main.ts`'s комментарий у `NestFactory.create`): без него КАЖДЫЙ запрос
 * будет видеть адрес прокси, эта функция честно вернёт `null` для всех
 * (прокси не в базе GeoIP), и любая `targetCountries`-кампания молча
 * перестанет показываться вообще всем — не ошибка этой функции, а
 * недонастроенное развёртывание.
 */
export function resolveVisitorCountry(ip: string | undefined): string | null {
  if (!ip) return null;
  const result = geoip.lookup(ip);
  return result?.country ?? null;
}
