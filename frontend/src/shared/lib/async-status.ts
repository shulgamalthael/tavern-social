/**
 * Единый статус для любых данных, которые в перспективе приходят с сервера.
 * `idle` — запрос ещё не запускался, `loading` — выполняется, `success` —
 * успешно завершён (данные могут быть пустым списком — это не ошибка),
 * `error` — запрос завершился неудачно.
 */
export type AsyncStatus = 'idle' | 'loading' | 'success' | 'error';
